const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const { execFileSync } = require('node:child_process')
const { _electron: electron } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
 const env={...process.env};delete env.ELECTRON_RUN_AS_NODE
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'toolbar-debug-'))
 let app;const errors=[]
 try {
  app=await electron.launch({executablePath:process.env.OCR_E2E_EXECUTABLE,args:[`--user-data-dir=${dir}`,process.env.OCR_E2E_PDF],env,timeout:60000})
  const page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message))
  await page.locator('#pdf-stage .stage-page[data-current] canvas').waitFor({state:'visible',timeout:60000})
  const toolbar=page.getByRole('toolbar',{name:'PDF 编辑工具栏'})
  const buttons=await toolbar.locator('button').evaluateAll(bs=>bs.map(b=>({text:b.textContent.trim(),aria:b.getAttribute('aria-label'),title:b.title})))
  assert(buttons.some(b=>b.text==='打开'));assert(buttons.some(b=>b.text==='保存'));assert(buttons.some(b=>b.text==='另存'))
  const blank=toolbar.getByRole('button',{name:'新建空白页',exact:true})
  assert.equal((await blank.textContent()).trim(),'')
  const toggle=toolbar.getByRole('switch')
  await toggle.waitFor()
  const before=await toggle.getAttribute('aria-checked')
  await toggle.click()
  assert.equal(await toggle.getAttribute('aria-checked'),before==='true'?'false':'true')
  await page.locator(before==='true'?'.stage__pages--single':'.stage__pages--continuous').waitFor()
  await toggle.focus();await page.keyboard.press('Space')
  assert.equal(await toggle.getAttribute('aria-checked'),before)
  await toolbar.getByRole('button',{name:'双页视图',exact:true}).click()
  await page.locator('.stage__pages--spread').waitFor()
  assert.equal(await toggle.getAttribute('aria-checked'),'false')
  assert((await toggle.getAttribute('title')).includes('双页'))
  const modes=await page.locator('.statusbar__zoom button').evaluateAll(bs=>bs.map(b=>({name:b.getAttribute('aria-label'),svg:b.querySelector('svg')?.innerHTML})))
  const width=modes.find(b=>b.name==='适合宽度');const fit=modes.find(b=>b.name==='适合页面')
  assert(width && fit && width.svg!==fit.svg)
  await page.locator('.statusbar__zoom').getByRole('button',{name:'适合宽度',exact:true}).click()
  await page.locator('.stage__pages--spread').waitFor()
  const output=process.env.OCR_E2E_SCREENSHOTS || os.tmpdir()
  for(const width of [1460,900]) {
   await app.evaluate(({BrowserWindow},width)=>{const w=BrowserWindow.getAllWindows()[0];if(w.isMaximized())w.unmaximize();w.setSize(width,900)},width)
   await page.waitForTimeout(300)
   const layout=await page.evaluate(()=>({width:innerWidth,documentWidth:document.documentElement.scrollWidth,toolbar:document.querySelector('.toolbar').getBoundingClientRect().toJSON()}))
   assert(layout.documentWidth<=layout.width+1,'Document horizontally overflows')
   assert(layout.toolbar.right<=layout.width+1,'Toolbar extends beyond viewport')
   await page.screenshot({path:path.join(output,`toolbar-${width}.png`)})
  }
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({ok:true,buttons,modes,errors}))
 } finally {if(app)try{execFileSync('taskkill.exe',['/PID',String(app.process().pid),'/T','/F'],{stdio:'ignore'})}catch{};try{fs.rmSync(dir,{recursive:true,force:true})}catch{}}
})().then(()=>process.exit(0)).catch(e=>{console.error(e);process.exit(1)})
