import { readFileSync } from 'node:fs'
import { PDFDocument } from 'pdf-lib'
import { GlobalWorkerOptions } from 'pdfjs-dist'
import { expect, it, vi } from 'vitest'
import { cloneWorkspaceTransfer } from './useWorkspace'
import { composePdf, getPdfDocument, inspectPdf, pagesForSource, releasePdfDocument } from '../lib/pdf'
import { decryptPdfBytes } from '../lib/pdfSecurity'

// qpdf-run requires a browser Web Worker. Exercise the real PDF.js password
// handshake and compose path, substituting just the worker's plaintext output.
vi.mock('../lib/pdfSecurity', () => ({ decryptPdfBytes: vi.fn() }))

it('keeps an unlocked transfer readable and editable after the originating workspace releases it', async () => {
  GlobalWorkerOptions.workerSrc = new URL('../../node_modules/pdfjs-dist/build/pdf.worker.min.mjs', import.meta.url).href
  // Generated by pypdf: one blank 144 x 288 page, AES-128; public test password.
  const encrypted = new Uint8Array(readFileSync(new URL('../../tests/fixtures/save-protected.pdf', import.meta.url)))
  const plain = await PDFDocument.create()
  plain.addPage([144, 288])
  vi.mocked(decryptPdfBytes).mockResolvedValue(await plain.save())
  const prompt = vi.fn(async () => 'fixture-open')
  const source = await inspectPdf(encrypted, 'synthetic.pdf', undefined, false, prompt)
  const clone = cloneWorkspaceTransfer({ pages: pagesForSource(source), sources: [source], suggestedName: 'copy', scopeLabel: 'all' })
  await releasePdfDocument(source)
  try {
    expect(source.documentInfo?.encrypted).toBe(true)
    expect(clone.sources[0].bytes).toBe(encrypted)
    expect(clone.sources[0]).not.toHaveProperty('password')
    expect(await getPdfDocument(clone.sources[0])).toHaveProperty('numPages', 1)
    const result = await PDFDocument.load(await composePdf(clone.pages, clone.sources))
    expect(result.getPage(0).getSize()).toEqual({ width: 144, height: 288 })
    expect(decryptPdfBytes).toHaveBeenCalledWith(encrypted, 'fixture-open')
    expect(prompt).toHaveBeenCalledOnce()
    await expect(PDFDocument.load(encrypted)).rejects.toThrow(/encrypted/)
  } finally { await releasePdfDocument(clone.sources[0]) }
})
